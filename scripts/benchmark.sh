#!/usr/bin/env bash
# Benchmark the mise check tasks and print a markdown report.
#
# Every measurement is a single warm run. `mise run` also runs `pnpm install`
# through [deps.pnpm] auto = true, so a few hundred milliseconds of dependency
# checking is included in each number. Aggregates use --continue-on-error so a
# red task does not abort the rest of the graph.
#
# The suite is large, so the run is split with BENCH_SECTION:
#   BENCH_SECTION=root  root tasks only
#   BENCH_SECTION=ws    per-workspace tasks only
#   unset               both
#
# Usage: BENCH_SECTION=root bash scripts/benchmark.sh > /tmp/bench-root.md
set -uo pipefail

cd "$(dirname "$0")/.."

SECTION="${BENCH_SECTION:-all}"
WORKSPACES=(
	extensions/leaf-copy
	extensions/repo-query
	extensions/sillajje
	extensions/stale-write-guard
	packages/pi-subagent
)

now_ms() { date +%s%N; }

run() {
	local label="$1"
	shift
	local start end code
	start=$(now_ms)
	"$@" >/dev/null 2>&1
	code=$?
	end=$(now_ms)
	printf '| %s | %d | %d |\n' "$label" $(((end - start) / 1000000)) "$code"
}

mr() { mise run --continue-on-error "$@"; }

printf 'Generated by `scripts/benchmark.sh` on %s.\n\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
printf 'Node %s, pnpm %s. Single warm run per command.\n\n' "$(node --version)" "$(pnpm --version)"

mr //:format >/dev/null 2>&1 || true
mr //:lint >/dev/null 2>&1 || true

if [[ "$SECTION" == "all" || "$SECTION" == "root" ]]; then
	printf '## Root tasks\n\n| Command | ms | exit |\n| --- | ---: | ---: |\n'
	run '`mise run //:format`' mr //:format
	run '`mise run //:lint`' mr //:lint
	run '`mise run //:typecheck`' mr //:typecheck
	run '`mise run //:typecheck-tests`' mr //:typecheck-tests
	run '`mise run //:typecheck-strict`' mr //:typecheck-strict
	run '`mise run //:boundaries`' mr //:boundaries
	run '`mise run //:knip`' mr //:knip
	run '`mise run //:ast-grep`' mr //:ast-grep
	run '`mise run //:type-aware`' mr //:type-aware
	run '`mise run //:semgrep`' mr //:semgrep
	run '`mise run //:test` (hermetic)' mr //:test
	run '`mise run //:test-external` (non-hermetic)' mr //:test-external
	run '`mise run //:check`' mr //:check
	run '`mise run //:ci`' mr //:ci
fi

if [[ "$SECTION" == "all" || "$SECTION" == "ws" ]]; then
	printf '\n## Per workspace\n\n| Command | ms | exit |\n| --- | ---: | ---: |\n'
	for ws in "${WORKSPACES[@]}"; do
		run "\`mise run //$ws:lint\`" mr "//$ws:lint"
		run "\`mise run //$ws:typecheck\`" mr "//$ws:typecheck"
		run "\`mise run //$ws:typecheck-strict\`" mr "//$ws:typecheck-strict"
		run "\`mise run //$ws:test\`" mr "//$ws:test"
		run "\`mise run //$ws:type-aware\`" mr "//$ws:type-aware"
		run "\`mise run //$ws:check\`" mr "//$ws:check"
		run "\`mise run //$ws:ci\`" mr "//$ws:ci"
	done
fi
